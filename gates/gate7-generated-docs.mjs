/**
 * Gate 7: the generated node reference matches the catalogue it comes from.
 *
 * `docs/nodes/*.md` is generated by `scripts/generate-node-docs.mjs`, and the
 * catalogue is also what the in-app Guide tab reads. Nothing checked the two
 * agreed, so twice in one day a catalogue edit shipped with a stale reference
 * beside it: the code node's help still offered TypeScript after it was
 * removed, and the webhook node's still said nothing about reachability after
 * that was written. Both were invisible because the docs are not hand-edited -
 * there is nothing in a diff to notice missing.
 *
 * Renders in memory and compares. Never writes: a gate that fixed the tree
 * would hide the very drift it is meant to report.
 */
import { readFileSync, existsSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { renderNodeDocs } from '../scripts/node-docs.mjs';

export function runGeneratedDocsGate(root) {
  const violations = [];
  const cataloguePath = join(root, 'packages/metis-catalogue/src/nodeTypes.v1.json');
  if (!existsSync(cataloguePath)) return violations;
  const outDir = join(root, 'docs', 'nodes');
  const expected = renderNodeDocs(JSON.parse(readFileSync(cataloguePath, 'utf8')));

  for (const [name, contents] of expected) {
    const path = join(outDir, name);
    if (!existsSync(path)) {
      violations.push({
        rule: 'missing',
        file: `docs/nodes/${name}`,
        detail: 'run node scripts/generate-node-docs.mjs',
      });
      continue;
    }
    if (readFileSync(path, 'utf8') !== contents) {
      violations.push({
        rule: 'stale',
        file: `docs/nodes/${name}`,
        detail: 'the catalogue changed; run node scripts/generate-node-docs.mjs',
      });
    }
  }
  // A node type removed from the catalogue must not leave its page behind.
  if (existsSync(outDir)) {
    for (const name of readdirSync(outDir)) {
      if (name.endsWith('.md') && !expected.has(name)) {
        violations.push({
          rule: 'orphan',
          file: `docs/nodes/${name}`,
          detail: 'no such node type; run node scripts/generate-node-docs.mjs',
        });
      }
    }
  }
  return violations;
}
